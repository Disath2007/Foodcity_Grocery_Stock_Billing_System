    private void btnaddActionPerformed(java.awt.event.ActionEvent evt) {
        // 1. Get text from the fields
        String username = txtUsername.getText();
        String password = txtUsername2.getText();
        String role = cmbRole.getSelectedItem().toString();
        String phone = txtPhone.getText();

        // 2. Simple check for empty fields
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill all fields!");
            return;
        }

        // 3. Database Save Logic (Beginner style)
        try {
            Connection conn = DatabaseConnection.getConnection();
            String sql = "INSERT INTO users (username, password, full_name, user_role, phone) VALUES (?, ?, ?, ?, ?)";
            // Note: full_name and user_role are guesses based on schema, but user only
            // added phone column.
            // Actually, checking schema:
            // username, password, full_name, phone, role

            sql = "INSERT INTO users (username, password, full_name, role, phone) VALUES (?, ?, ?, ?, ?)";

            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, username);
            pst.setString(2, password);
            pst.setString(3, username); // full_name = username
            pst.setString(4, role);
            pst.setString(5, phone);

            int rs = pst.executeUpdate();
            if (rs > 0) {
                JOptionPane.showMessageDialog(null, "Inserted Successfully!");
                loadUsers();
                clearFields();
            } else {
                System.out.println("Failed to Save");
            }
        } catch (Exception e) {
            System.out.println(e);
        }
    }

    private void btnupdateActionPerformed(java.awt.event.ActionEvent evt) {
        int selectedRow = usertable.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Select a user to update!");
            return;
        }

        String userId = usertable.getValueAt(selectedRow, 0).toString();
        String username = txtUsername.getText();
        String password = txtUsername2.getText();
        String role = cmbRole.getSelectedItem().toString();
        String phone = txtPhone.getText();

        try {
            Connection conn = DatabaseConnection.getConnection();
            String sql = "UPDATE users SET username=?, password=?, full_name=?, role=?, phone=? WHERE user_id=?";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, username);
            pst.setString(2, password);
            pst.setString(3, username); // full_name = username
            pst.setString(4, role);
            pst.setString(5, phone);
            pst.setString(6, userId);

            int rs = pst.executeUpdate();
            if (rs > 0) {
                JOptionPane.showMessageDialog(null, "Updated Successfully!");
                loadUsers();
                clearFields();
            }
        } catch (Exception e) {
            System.out.println(e);
        }
    }

