    // Method to load data to the table
    private void loadUsers() {
        try {
            DefaultTableModel dt = (DefaultTableModel) usertable.getModel();
            dt.setRowCount(0); // Clear current table

            Connection conn = DatabaseConnection.getConnection();
            Statement s = conn.createStatement();
            ResultSet rs = s.executeQuery("SELECT * FROM users");

            while (rs.next()) {
                Object[] row = {
                        rs.getString("user_id"),
                        rs.getString("username"),
                        rs.getString("role"),
                        rs.getString("phone"),
                        rs.getString("created_at")
                };
                dt.addRow(row);
            }
        } catch (Exception e) {
            System.out.println(e);
        }
    }

    // Method to clear the input fields
    private void clearFields() {
        txtUsername.setText("");
        txtUsername2.setText("");
        cmbRole.setSelectedIndex(0);
        txtsearch.setText("");
        txtPhone.setText("");
    }

    // Logic for Search (Simplified)
    private void searchUsers() {
        String search = txtsearch.getText();
        try {
            DefaultTableModel dt = (DefaultTableModel) usertable.getModel();
            dt.setRowCount(0);

            Connection conn = DatabaseConnection.getConnection();
            Statement s = conn.createStatement();
            ResultSet rs = s.executeQuery(
                    "SELECT * FROM users WHERE username LIKE '%" + search + "%' OR user_id LIKE '%" + search + "%' ");

            while (rs.next()) {
                Object[] row = {
                        rs.getString("user_id"),
                        rs.getString("username"),
                        rs.getString("role"),
                        rs.getString("phone"),
                        rs.getString("created_at")
                };
                dt.addRow(row);
            }
        } catch (Exception e) {
            System.out.println(e);
        }
    }

