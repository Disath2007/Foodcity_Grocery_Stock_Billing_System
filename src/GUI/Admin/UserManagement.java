    private void usertableMouseClicked(java.awt.event.MouseEvent evt) {// GEN-FIRST:event_usertableMouseClicked
        // 1. Get the selected row index
        int selectedRow = usertable.getSelectedRow();

        // 2. Pull data from the table into the text fields
        String username = usertable.getValueAt(selectedRow, 1).toString();
        String role = usertable.getValueAt(selectedRow, 2).toString();

        Object phoneObj = usertable.getValueAt(selectedRow, 3);
        String phone = (phoneObj != null) ? phoneObj.toString() : "";

        txtUsername.setText(username);
        cmbRole.setSelectedItem(role);
        txtPhone.setText(phone);

        // 3. Simple try-catch to get the password from the database
        try {
            String id = usertable.getValueAt(selectedRow, 0).toString();
            Connection conn = DatabaseConnection.getConnection();
            Statement s = conn.createStatement();
            ResultSet rs = s.executeQuery("SELECT password FROM users WHERE user_id = '" + id + "'");

            if (rs.next()) {
                txtUsername2.setText(rs.getString("password"));
            }
        } catch (Exception e) {
            System.out.println(e);
        }
    }// GEN-LAST:event_usertableMouseClicked

