    private void btndeleteActionPerformed(java.awt.event.ActionEvent evt) {
        // 1. Get the information from the table
        int selectedRow = usertable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Please select a user to delete!");
            return;
        }

        String userId = usertable.getValueAt(selectedRow, 0).toString();
        String role = usertable.getValueAt(selectedRow, 2).toString();

        // 2. Prevent deleting Admin
        if (role.equalsIgnoreCase("Admin")) {
            JOptionPane.showMessageDialog(null, "Admin users cannot be deleted!");
            return;
        }

        // 3. Confirm and Delete
        int confirm = JOptionPane.showConfirmDialog(null, "Are you sure?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = DatabaseConnection.getConnection();
                PreparedStatement pst = conn.prepareStatement("DELETE FROM users WHERE user_id = ?");
                pst.setString(1, userId);

                int rs = pst.executeUpdate();
                if (rs > 0) {
                    JOptionPane.showMessageDialog(null, "Deleted Successfully!");
                    loadUsers();
                    clearFields();
                }
            } catch (Exception e) {
                System.out.println(e);
            }
        }
    }

